// .ini ファイル キーワード有効文字範囲
// キーワードには 'a'～'z' と 'A'～'Z' および '_' が使用可能とする
#define INIF_KEY_C_MIN_0 0x41 // 'A'：キー認識文字コード最小値
#define INIF_KEY_C_MAX_0 0x5A // 'Z'：キー認識文字コード最大値
#define INIF_KEY_C_MIN_1 0x5F // '_'：キー認識文字コード最小値
#define INIF_KEY_C_MAX_1 0x5F // '_'：キー認識文字コード最大値
#define INIF_KEY_C_MIN_2 0x61 // 'a'：キー認識文字コード最小値
#define INIF_KEY_C_MAX_2 0x7A // 'z'：キー認識文字コード最大値

// 取得した文字コードが有効なキーワード文字かを判定する (TRUE : 有効 / FALSE : 無効)
#define IS_KEY_CHAR(c) \
    (((c) >= INIF_KEY_C_MIN_0 && (c) <= INIF_KEY_C_MAX_0) || \
     ((c) >= INIF_KEY_C_MIN_1 && (c) <= INIF_KEY_C_MAX_1) || \
     ((c) >= INIF_KEY_C_MIN_2 && (c) <= INIF_KEY_C_MAX_2))

// .iniファイル読み取り時のキーワード文字格納バッファ容量
#define KEY_BUF_SIZE     32

//============================================================================================
// 型定義 (内部用)
//============================================================================================

//============================================================================================
// プロトタイプ宣言 (static)
//============================================================================================

//============================================================================================
// グローバル変数定義 (外部公開)
//============================================================================================

//============================================================================================
