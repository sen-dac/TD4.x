// 定数定義 (内部用)
//============================================================================================
// MFPレジスタ (Inside X68000 P.81)
#define U1_MFP_GPIP  (*((volatile U1*)0xE88001))  // GPIP：V-DISP,OPM割り込みetc...

//============================================================================================
