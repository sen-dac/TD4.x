#include "main.h"

//============================================================================================
// 定数定義 (内部用)
//============================================================================================
// APIのパラメータ
#define SUPER_ON    0    // (P.158) B_SUPER() : スーパーバイザモード ON
#define EXIT_NORMAL 0    // (P.338) exit()    : 実行中プロセスの正常終了

//============================================================================================
// 型定義 (内部用)
//============================================================================================

//============================================================================================
// プロトタイプ宣言 (static)
//============================================================================================

//============================================================================================
// グローバル変数定義 (外部公開)
//============================================================================================

//============================================================================================
// 静的変数定義 (static)
//============================================================================================

//============================================================================================
// 関数定義
//============================================================================================
//============================================================================================
// アプリケーションのエントリポイント
//--------------------------------------------------------------------------------------------
// Arguments : int   argc   : (I) 受け取ったコマンドライン引数の数
//             char* argv[] : (I) コマンドライン引数(文字列)配列先頭アドレス
//                                [0]にはこのプログラム名が入る
// Return    : int          : (O) 常に 0
//--------------------------------------------------------------------------------------------
// Note      :
// C言語の標準仕様に準じて int main(int argc, char *argv[]) と定義する。
// ただし exit(0) が呼ばれた時点でプロセスが終了するため return に到達することはない。
//
// B_SUPER()の戻り値はCライブラリマニュアル(P.158)にintと記載されている。
// GCC真里子版(ver1.42)において、int型は符号付き4バイト型である事を確認済み。
// このため、S4型(typedef signed long S4)で受け取る。
//============================================================================================
int main(int argc, char* argv[])
{
    // 初期化処理
    S4  s4_ssp  = B_SUPER(SUPER_ON);             // スーパーバイザモード
    U1* u1p_mem = u1pf_g_MemGetPt();             // ターゲットCPU上で動作するメモリ領域を取得

    vdf_g_CpuReset(RST_TYPE_COLD);               // ターゲットCPUをパワーオンリセット
    vdf_g_DbgInit(argc, argv, u1p_mem);          // デバッガ初期化

    // 実行処理
    while(TRUE)                                  // メインループ
    {
        if(s1f_g_DbgRun(u1p_mem) == S1_RET_QUIT) // アプリ終了通知を受け取った場合
        break;                                   // メインループを抜けて終了処理へ
    }

    // 終了処理
    B_SUPER(s4_ssp);                             // スーパーバイザモード OFF
    KFLUSHIO(KFL_BUFCLR);                        // キーバッファのクリア
    exit(EXIT_NORMAL);                           // プロセス終了 (以降の処理は実行されない)

    return 0;                                    // 不到達処理だがC言語の標準仕様に準ずる
}
