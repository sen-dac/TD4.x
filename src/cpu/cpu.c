// 本来のCPU動作とは異なるデバッグ用機能
//============================================================================================
VD vdf_g_CpuDebugDecPc(VD)
{
    st_s_RegPC.u4_val --;                             // プログラムカウンタ減算
    st_s_RegPC.u4_val &= st_s_RegPC.u4_max;           // 有効ビットをマスク
}

//============================================================================================
// [デバッグ機能] プログラムカウンタの値を取得する
//--------------------------------------------------------------------------------------------
// Arguments : -
// Return    : U4 u4_ret : (O) プログラムカウンタの値
//--------------------------------------------------------------------------------------------
