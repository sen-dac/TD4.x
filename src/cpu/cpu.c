VD vdf_g_CpuDebugIncPc(VD)

{
    st_s_RegPC.u4_val ++;                             // プログラムカウンタ加算
    st_s_RegPC.u4_val &= st_s_RegPC.u4_max;           // 有効ビットをマスク
}

//============================================================================================
// [デバッグ機能] プログラムカウンタを1つ戻す
